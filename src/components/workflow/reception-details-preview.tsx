import { Badge } from "@/components/ui/badge";
import { Card } from "@/components/ui/card";
import { DocumentPreview } from "@/components/workflow/document-preview";
import type { ReceptionFormValues } from "@/components/workflow/reception-form";
import { ACCESS_PURPOSE_LABELS } from "@/lib/domain/types";
import type { Document } from "@/lib/services/document-service";

// What the visitor submitted, read-only, grouped exactly as they filled it in.
// It renders the *same* parsed values the edit form is prefilled with, so the
// two views can never disagree about what was submitted.
//
// Separate from `ReceptionSummary`, which is Hospital's view of an existing
// Engagement (9 fields plus stakeholder approval); the field styling is
// deliberately identical so the two read as one system.
type ReceptionDetailsPreviewProps = {
  values: Partial<ReceptionFormValues>;
  // Only set for a submission that hasn't become an Engagement yet: it drives
  // the type badge and hides the fields a Local form never asks. An
  // Engagement has no registration type — it belongs to a Person — so the
  // full set renders.
  registrationType?: string;
  department?: string;
  // Reception's own bookkeeping, which only exists once an Engagement does.
  showAdministration?: boolean;
  documentsTitle?: string;
  // Each document paired with a signed preview URL, generated by the page.
  // Null when the URL couldn't be signed — the card then shows a file icon
  // and still offers Download.
  documents: { document: Document; previewUrl: string | null }[];
};

function text(value: string | undefined): string {
  return value && value.length > 0 ? value : "—";
}

function yesNo(value: boolean | undefined): string {
  return value === true ? "Yes" : "No";
}

export function ReceptionDetailsPreview({
  values,
  registrationType,
  department,
  showAdministration = false,
  documentsTitle = "Documents Supplied",
  documents,
}: ReceptionDetailsPreviewProps) {
  const isLocal = registrationType === "Local";

  return (
    <div className="flex flex-col gap-6">
      <Card className="flex flex-col gap-4 p-6">
        <div className="flex items-center justify-between">
          <h2 className="text-lg font-semibold text-foreground">
            Visitor Details
          </h2>
          {registrationType && (
            <Badge variant="outline" className="text-muted-foreground">
              {registrationType}
            </Badge>
          )}
        </div>
        <div className="grid grid-cols-3 gap-4">
          <Field label="Full Name" value={text(values.fullName)} />
          <Field
            label={isLocal ? "Ghana Card No." : "Passport No."}
            value={text(values.passportNo)}
          />
          <Field label="Date of Birth" value={text(values.dateOfBirth)} />
          <Field label="Gender" value={text(values.gender)} />
          {!isLocal && (
            <Field label="Nationality" value={text(values.nationality)} />
          )}
          <Field label="Email Address" value={text(values.email)} />
          <Field label="Telephone (Off Site)" value={text(values.phone)} />
          <Field
            label="Telephone (On Site)"
            value={text(values.telephoneOnSite)}
          />
          <Field
            label="Employment Status"
            value={text(values.employmentStatus)}
          />
          <Field
            label="Emergency Contact"
            value={`${text(values.emergencyContactName)} — ${text(values.emergencyContactPhone)}`}
          />
          <Field
            label="Nature of Visit"
            value={
              values.accessPurpose
                ? ACCESS_PURPOSE_LABELS[values.accessPurpose]
                : "—"
            }
          />
        </div>
      </Card>

      <Card className="flex flex-col gap-4 p-6">
        <h2 className="text-lg font-semibold text-foreground">
          Company Details
        </h2>
        <div className="grid grid-cols-3 gap-4">
          <Field label="Company Name" value={text(values.companyName)} />
          <Field
            label="Contact (Monthly Reporting)"
            value={text(values.contactNameMonthly)}
          />
          <Field label="Contact Email" value={text(values.contactEmail)} />
          <Field
            label="Emergency Contact (Company)"
            value={text(values.companyEmergencyName)}
          />
          <Field
            label="Emergency Tel. (Company)"
            value={text(values.companyEmergencyTel)}
          />
        </div>
      </Card>

      <Card className="flex flex-col gap-4 p-6">
        <h2 className="text-lg font-semibold text-foreground">
          Access Details
        </h2>
        <div className="grid grid-cols-3 gap-4">
          <Field
            label="GMC Liaison Person"
            value={text(values.gmcLiaisonPerson)}
          />
          <Field
            label="GMC Liaison Department"
            value={text(values.gmcLiaisonDept ?? department)}
          />
          <Field label="Access Level" value={text(values.accessLevel)} />
          <Field label="Date of Arrival" value={text(values.arrivalDate)} />
          <Field label="Date of Departure" value={text(values.departureDate)} />
          {!isLocal && (
            <Field label="Visa Type" value={text(values.visaType)} />
          )}
          <div className="col-span-3">
            <Field
              label="Reason for Request"
              value={text(values.reasonForRequest)}
            />
          </div>
        </div>
      </Card>

      <Card className="flex flex-col gap-4 p-6">
        <h2 className="text-lg font-semibold text-foreground">
          Site Support Requirements
        </h2>
        <div className="grid grid-cols-3 gap-4">
          <Field
            label="Airport Pickup"
            value={yesNo(values.airportPickup)}
            muted={values.airportPickup !== true}
          />
          {values.airportPickup === true && (
            <Field label="Pickup Date" value={text(values.pickupDate)} />
          )}
          <Field
            label="Transport Required To"
            value={yesNo(values.transportTo)}
            muted={values.transportTo !== true}
          />
          <Field
            label="Transport Required From"
            value={yesNo(values.transportFrom)}
            muted={values.transportFrom !== true}
          />
          <Field
            label="Accommodation Required"
            value={yesNo(values.accommodationRequired)}
            muted={values.accommodationRequired !== true}
          />
          {values.accommodationRequired === true && (
            <Field
              label="Accommodation Location"
              value={text(values.accommodationLocation)}
            />
          )}
          <Field
            label="Permanent Access Badge"
            value={yesNo(values.permanentAccessBadge)}
            muted={values.permanentAccessBadge !== true}
          />
          {!isLocal && (
            <Field
              label="Ghana Visa Required"
              value={yesNo(values.ghanaVisaRequired)}
              muted={values.ghanaVisaRequired !== true}
            />
          )}
          <Field
            label="General Site Induction"
            value={yesNo(values.generalSiteInduction)}
            muted={values.generalSiteInduction !== true}
          />
          <Field
            label="Other Inductions"
            value={yesNo(values.otherInductions)}
            muted={values.otherInductions !== true}
          />
          <Field
            label="Bringing Equipment"
            value={yesNo(values.bringingEquipment)}
            muted={values.bringingEquipment !== true}
          />
          <Field
            label="PPE Required"
            value={yesNo(values.ppeRequired)}
            muted={values.ppeRequired !== true}
          />
          <Field
            label="IT Access Required"
            value={yesNo(values.itAccessRequired)}
            muted={values.itAccessRequired !== true}
          />
        </div>
      </Card>

      {showAdministration && (
        <Card className="flex flex-col gap-4 p-6">
          <h2 className="text-lg font-semibold text-foreground">
            Administration
          </h2>
          <div className="grid grid-cols-3 gap-4">
            <Field
              label="Accommodation Confirmed"
              value={yesNo(values.accommodationConfirmed)}
              muted={values.accommodationConfirmed !== true}
            />
            <Field
              label="Itinerary Attached"
              value={yesNo(values.itineraryAttached)}
              muted={values.itineraryAttached !== true}
            />
            <Field
              label="Inflight Updated"
              value={yesNo(values.inflightUpdated)}
              muted={values.inflightUpdated !== true}
            />
            <div className="col-span-3">
              <Field
                label="Remarks / Other Information"
                value={text(values.remarks)}
              />
            </div>
          </div>
        </Card>
      )}

      <Card className="flex flex-col gap-4 p-6">
        <h2 className="text-lg font-semibold text-foreground">
          {documentsTitle}
        </h2>
        {documents.length === 0 ? (
          <p className="text-sm text-muted-foreground">
            The visitor attached no documents.
          </p>
        ) : (
          <div className="grid grid-cols-4 gap-8 pt-2">
            {documents.map(({ document, previewUrl }) => (
              <DocumentPreview
                key={document.id}
                document={document}
                previewUrl={previewUrl}
              />
            ))}
          </div>
        )}
      </Card>
    </div>
  );
}

function Field({
  label,
  value,
  muted = false,
}: {
  label: string;
  value: string;
  muted?: boolean;
}) {
  return (
    <div className="flex flex-col gap-1">
      <span className="text-xs font-medium text-muted-foreground">{label}</span>
      <span
        className={
          muted ? "text-sm text-muted-foreground" : "text-sm text-foreground"
        }
      >
        {value}
      </span>
    </div>
  );
}
